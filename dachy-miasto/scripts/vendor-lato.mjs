// Stores the Lato typeface locally (SIL Open Font License 1.1) so the app keeps working offline.
// Lato is the typeface of the Kraków city portals; the app uses it to sit visually next to them.
import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';

const destination = new URL('../vendor/lato/', import.meta.url);
const css = 'https://fonts.googleapis.com/css2?family=Lato:ital,wght@0,400;0,700;0,900;1,400&display=swap';
const license = 'https://raw.githubusercontent.com/google/fonts/main/ofl/lato/OFL.txt';
// A current browser user agent makes the API return WOFF2 files split into unicode subsets.
const agent = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const get = async url => {
  const response = await fetch(url, { headers: { 'user-agent': agent }, signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`HTTP ${response.status}: ${url}`);
  return Buffer.from(await response.arrayBuffer());
};

await fs.mkdir(destination, { recursive: true });
const source = (await get(css)).toString('utf8');
const manifest = { name: 'Lato', license: 'OFL-1.1', source: css, files: {} };
let local = '/* Lato (SIL Open Font License 1.1, see OFL.txt). Generated by scripts/vendor-lato.mjs. */\n';
for (const block of source.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face \{([^}]+)\}/g)) {
  const [, subset, body] = block;
  if (!['latin', 'latin-ext'].includes(subset)) continue;
  const url = body.match(/url\((https:[^)]+\.woff2)\)/)[1];
  const style = body.match(/font-style: (\w+)/)[1], weight = body.match(/font-weight: (\d+)/)[1];
  const file = `lato-${weight}${style === 'italic' ? 'i' : ''}-${subset}.woff2`;
  const content = await get(url);
  await fs.writeFile(new URL(file, destination), content);
  manifest.files[file] = { url, sha256Base64: createHash('sha256').update(content).digest('base64'), bytes: content.length };
  local += `/* ${subset} */\n@font-face{font-family:'Lato';font-style:${style};font-weight:${weight};font-display:swap;src:url(./${file}) format('woff2');unicode-range:${body.match(/unicode-range: ([^;]+);/)[1]}}\n`;
}
await fs.writeFile(new URL('lato.css', destination), local);
await fs.writeFile(new URL('OFL.txt', destination), await get(license));
await fs.writeFile(new URL('manifest.json', destination), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Vendored Lato: ${Object.keys(manifest.files).length} files.`);
